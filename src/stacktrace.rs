fn strip_crate_version(name_ver: &str) -> &str {
    // Find `-<digit>` separator starting the semver version.
    let bytes = name_ver.as_bytes();
    for (idx, _) in name_ver.match_indices('-') {
        if bytes.get(idx + 1).is_some_and(u8::is_ascii_digit) {
            return &name_ver[..idx];
        }
    }
    name_ver
}

