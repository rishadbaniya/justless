    #[test]
    fn small_runs_redacted_frames_patch_hunks_and_numbered_lists_stay_verbatim() {
        // Fewer than 3 external frames -> untouched.
        let short = concat!(
            "Error: boom\n",
            "    at throwSite (node:net:10:1)\n",
            "    at ext1 (/app/node_modules/pg/a.js:1:1)\n",
            "    at ext2 (/app/node_modules/pg/b.js:2:1)\n",
            "    at user (/app/src/app.ts:5:1)\n",
        );
        assert_eq!(
            collapse(short, Some(Path::new("/app")), Some("stderr")),
            None
        );

        // Redacted secret inside an external frame is never hidden.
        let redacted = concat!(
            "Error: auth failed\n",
            "    at throwSite (node:net:10:1)\n",
            "    at a (/app/node_modules/pg/a.js:1:1)\n",
            "    at b (/app/node_modules/pg/b.js:2:1) [redacted:secret:abcd]\n",
            "    at c (/app/node_modules/pg/c.js:3:1)\n",
            "    at d (/app/node_modules/pg/d.js:4:1)\n",
        );
        assert_eq!(
            collapse(redacted, Some(Path::new("/app")), Some("stderr")),
            None
        );

        // Patch hunks are never modified even if they contain stack traces.
        let patch = concat!(
            "@@ -1,5 +1,5 @@\n",
            "+    at throwSite (node:net:10:1)\n",
            "+    at a (/app/node_modules/pg/a.js:1:1)\n",
            "+    at b (/app/node_modules/pg/b.js:2:1)\n",
            "+    at c (/app/node_modules/pg/c.js:3:1)\n",
            "+    at d (/app/node_modules/pg/d.js:4:1)\n",
        );
        assert_eq!(
            collapse(patch, Some(Path::new("/app")), Some("stdout")),
            None
        );

        // Ordinary numbered lists are not mistaken for Rust backtraces.
        let list = "   0: alpha\n   1: beta\n   2: gamma\n   3: delta\n   4: epsilon\n";
        assert_eq!(collapse(list, None, Some("stdout")), None);
    }

